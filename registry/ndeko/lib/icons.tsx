import {
  HugeiconsIcon,
  type HugeiconsIconProps,
  type IconSvgElement,
} from '@hugeicons/react';

export type IconProps = Omit<HugeiconsIconProps, 'icon'>;

export type Icon = React.ComponentType<IconProps>;

const DEFAULT_STROKE_WIDTH = 1.75;

function createIcon(glyph: IconSvgElement, displayName: string): Icon {
  function NamedIcon({
    strokeWidth = DEFAULT_STROKE_WIDTH,
    ...props
  }: IconProps) {
    return (
      <HugeiconsIcon
        icon={glyph}
        strokeWidth={strokeWidth}
        aria-hidden='true'
        {...props}
      />
    );
  }
  NamedIcon.displayName = displayName;
  return NamedIcon;
}

