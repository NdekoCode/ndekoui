import fs from 'node:fs';
import path from 'node:path';

import { getMapJSON } from 'dotted-map';

const OUTPUT = path.join(__dirname, '../components/core/dotted-map-points.ts');

const GRID_ROWS = 40;

const REGION = {
  lat: { min: -56, max: 80 },
  lng: { min: -180, max: 180 },
};

const EARTH_RADIUS = 6378137;

const METRES_PER_DEGREE = (EARTH_RADIUS * Math.PI) / 180;

type GridPoint = { x: number; y: number };

type GridMap = {
  points: Record<string, GridPoint>;
  width: number;
  height: number;
  ystep: number;
  X_MIN: number;
  X_RANGE: number;
  Y_MAX: number;
  Y_RANGE: number;
};

type Run = { y: number; start: number; end: number };

function rounded(value: number, digits: number) {
  const factor = 10 ** digits;
  const scaled = Math.round(value * factor);
  return scaled / factor;
}

function rowsOf(points: GridPoint[], ystep: number) {
  const rows = new Map<number, number[]>();
  for (const point of points) {
    const row = Math.round(point.y / ystep);
    const columns = rows.get(row) ?? [];
    columns.push(point.x);
    rows.set(row, columns);
  }
  return rows;
}

function runsOfRow(y: number, columns: number[]) {
  const sorted = [...columns].sort((left, right) => left - right);
  const runs: Run[] = [];
  for (const x of sorted) {
    const last = runs.at(-1);
    const continuesLast = last !== undefined && x - last.end === 1;
    if (continuesLast) {
      last.end = x;
      continue;
    }
    runs.push({ y, start: x, end: x });
  }
  return runs;
}

function segmentOf(run: Run) {
  const length = run.end - run.start;
  return `M${run.start} ${run.y}h${length}`;
}

function pathOf(map: GridMap) {
  const points = Object.values(map.points);
  const rows = rowsOf(points, map.ystep);
  const rowNumbers = [...rows.keys()].sort((left, right) => left - right);
  const segments: string[] = [];
  for (const row of rowNumbers) {
    const y = rounded(row * map.ystep, 2);
    const columns = rows.get(row) ?? [];
    const runs = runsOfRow(y, columns);
    segments.push(...runs.map(segmentOf));
  }
  return { path: segments.join(''), dotCount: points.length };
}

function boundsOf(map: GridMap) {
  const lngMin = map.X_MIN / METRES_PER_DEGREE;
  const lngMax = (map.X_MIN + map.X_RANGE) / METRES_PER_DEGREE;
  const latMax = map.Y_MAX / METRES_PER_DEGREE;
  const latMin = (map.Y_MAX - map.Y_RANGE) / METRES_PER_DEGREE;
  return {
    lngMin: rounded(lngMin, 4),
    lngMax: rounded(lngMax, 4),
    latMin: rounded(latMin, 4),
    latMax: rounded(latMax, 4),
  };
}

function boundsLinesOf(bounds: Record<string, number>) {
  const entries = Object.entries(bounds);
  return entries.map(([key, value]) => `  ${key}: ${value},`);
}

function moduleOf(map: GridMap) {
  const { path: dotsPath, dotCount } = pathOf(map);
  const bounds = boundsOf(map);
  const height = rounded(map.height, 2);
  return [
    '// Generated by scripts/generate-dotted-map.ts with dotted-map (MIT). Run the script again instead of editing this file.',
    `// ${dotCount} land dots on a diagonal grid, equirectangular, latitudes ${REGION.lat.min} to ${REGION.lat.max}.`,
    '',
    `export const DOTTED_MAP_WIDTH = ${map.width};`,
    '',
    `export const DOTTED_MAP_HEIGHT = ${height};`,
    '',
    'export const DOTTED_MAP_BOUNDS = {',
    ...boundsLinesOf(bounds),
    '} as const;',
    '',
    '/** One horizontal run of dots per subpath, one grid unit apart: draw it with a round-capped dash of `0 1`. */',
    'export const DOTTED_MAP_PATH =',
    `  '${dotsPath}';`,
    '',
  ].join('\n');
}

function generate() {
  const json = getMapJSON({
    height: GRID_ROWS,
    grid: 'diagonal',
    projection: { name: 'equirectangular' },
    region: REGION,
  });
  const map = JSON.parse(json) as GridMap;
  const source = moduleOf(map);
  fs.writeFileSync(OUTPUT, source);
  const size = Buffer.byteLength(source);
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} (${size} bytes)`);
}

generate();
