import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import type { CatalogCategory } from '../app/components/_catalog/types';
import type { RegistryItemDefinition } from '../registry/items';
import type { ComponentManifest } from '../registry/ndeko/components/types';
import { motionItemNameOf } from '../lib/site';

const ROOT = path.join(__dirname, '..');
const COMPONENTS_DIR = path.join(ROOT, 'registry/ndeko/components');
const HOOKS_DIR = path.join(ROOT, 'registry/ndeko/hooks');
const GENERATED_DIR = path.join(ROOT, 'app/components/_generated');

const LOCAL_PREFIX = '@/registry/ndeko/';
const MOTION_PREFIX = '@/components/core/';
const COMPONENTS_PREFIX = `${LOCAL_PREFIX}components/`;
const LOCAL_ITEM_FOLDERS = new Set(['ui', 'lib', 'hooks']);
const FRAMEWORK_PACKAGES = new Set(['react', 'react-dom', 'next']);
const SOURCE_EXTENSIONS = ['.tsx', '.ts'];
const GENERATED_NOTICE =
  '// Generated by scripts/build-registry.ts from the category manifests. Do not edit.';

const CATEGORY_NAMES: Record<string, string> = {
  'calendar-date-picker': 'Date picker',
  dropdown: 'Dropdown menu',
  subtask: 'Sub-task',
  aside: 'Side panel',
};

export function titleOf(slug: string) {
  const knownName = CATEGORY_NAMES[slug];
  if (knownName) {
    return knownName;
  }
  const sentence = slug.split('-').join(' ');
  return sentence.charAt(0).toUpperCase() + sentence.slice(1);
}

export function identifierOf(name: string) {
  const parts = name.split('-');
  const capitalized = parts.map(
    (part) => part.charAt(0).toUpperCase() + part.slice(1)
  );
  return capitalized.join('');
}

function importsOf(source: string) {
  const matches = source.matchAll(/from\s+['"]([^'"]+)['"]/g);
  return Array.from(matches, (match) => match[1]);
}

function packageNameOf(specifier: string) {
  const segments = specifier.split('/');
  const isScoped = specifier.startsWith('@');
  if (isScoped) {
    return segments.slice(0, 2).join('/');
  }
  return segments[0];
}

function localItemOf(specifier: string) {
  const relative = specifier.slice(LOCAL_PREFIX.length);
  const [folder, name] = relative.split('/');
  const isItemFolder = LOCAL_ITEM_FOLDERS.has(folder);
  if (!isItemFolder) {
    return null;
  }
  return name;
}

export function dependenciesOf(filePath: string) {
  const source = fs.readFileSync(filePath, 'utf8');
  const registryDependencies = new Set<string>(['theme']);
  const dependencies = new Set<string>();

  for (const specifier of importsOf(source)) {
    if (specifier.startsWith(MOTION_PREFIX)) {
      const motionSlug = specifier.slice(MOTION_PREFIX.length);
      registryDependencies.add(motionItemNameOf(motionSlug));
      continue;
    }
    if (specifier.startsWith(LOCAL_PREFIX)) {
      const itemName = localItemOf(specifier);
      if (itemName) {
        registryDependencies.add(itemName);
      }
      continue;
    }
    if (specifier.startsWith('.')) {
      continue;
    }
    const packageName = packageNameOf(specifier);
    if (FRAMEWORK_PACKAGES.has(packageName)) {
      continue;
    }
    dependencies.add(packageName);
  }

  return {
    registryDependencies: sortedAlphabetically(registryDependencies),
    dependencies: sortedAlphabetically(dependencies),
  };
}

export function sortedAlphabetically(values: Iterable<string>) {
  const list = Array.from(values);
  return list.sort((first, second) => first.localeCompare(second));
}

export function mergedDependencies(filePaths: string[]) {
  const registryDependencies = new Set<string>();
  const dependencies = new Set<string>();
  for (const filePath of filePaths) {
    const found = dependenciesOf(filePath);
    found.registryDependencies.forEach((name) =>
      registryDependencies.add(name)
    );
    found.dependencies.forEach((name) => dependencies.add(name));
  }
  return {
    registryDependencies: sortedAlphabetically(registryDependencies),
    dependencies: sortedAlphabetically(dependencies),
  };
}

function resolvedSourceOf(baseDir: string, specifier: string) {
  const base = path.resolve(baseDir, specifier);
  const fileCandidates = SOURCE_EXTENSIONS.map(
    (extension) => `${base}${extension}`
  );
  const indexCandidates = SOURCE_EXTENSIONS.map((extension) =>
    path.join(base, `index${extension}`)
  );
  const candidates = [...fileCandidates, ...indexCandidates];
  const existing = candidates.find((candidate) => fs.existsSync(candidate));
  return existing ?? null;
}

function partPathOf(fromFile: string, specifier: string) {
  if (specifier.startsWith('.')) {
    return resolvedSourceOf(path.dirname(fromFile), specifier);
  }
  if (specifier.startsWith(COMPONENTS_PREFIX)) {
    const pathFromRoot = specifier.slice('@/'.length);
    return resolvedSourceOf(ROOT, pathFromRoot);
  }
  return null;
}

/** Every composition file a composition reaches, through a relative import or the components alias, such as the shared parts of a category. */
function localPartsOf(entryFile: string) {
  const found = new Set<string>();
  const pending = [entryFile];
  let current = pending.pop();
  while (current) {
    const source = fs.readFileSync(current, 'utf8');
    for (const specifier of importsOf(source)) {
      const resolved = partPathOf(current, specifier);
      const isNew = resolved !== null && !found.has(resolved);
      if (isNew) {
        found.add(resolved);
        pending.push(resolved);
      }
    }
    current = pending.pop();
  }
  return sortedAlphabetically(found);
}

function targetedFileOf(absolutePath: string) {
  const pathInComponents = path.relative(COMPONENTS_DIR, absolutePath);
  return {
    path: path.relative(ROOT, absolutePath),
    type: 'registry:component' as const,
    target: `components/${pathInComponents}`,
  };
}

function isInsideComponents(filePath: string) {
  const relativePath = path.relative(COMPONENTS_DIR, filePath);
  const isOutside = relativePath.startsWith('..');
  return !isOutside;
}

/**
 * The catalogue files a block or a template imports, with their own parts. They install where the
 * catalogue item puts them, which is where the CLI rewrites `@/registry/ndeko/components/...` to.
 */
export function componentPartsOf(filePaths: string[]) {
  const found = new Set<string>();
  for (const filePath of filePaths) {
    const parts = localPartsOf(filePath);
    const catalogueParts = parts.filter(isInsideComponents);
    catalogueParts.forEach((part) => found.add(part));
  }
  const paths = sortedAlphabetically(found);
  const files = paths.map(targetedFileOf);
  return { paths, files };
}

function componentFilesOf(entryPath: string, parts: string[]) {
  if (parts.length === 0) {
    const relativePath = path.relative(ROOT, entryPath);
    return [{ path: relativePath, type: 'registry:component' as const }];
  }
  const allFiles = [entryPath, ...parts];
  return allFiles.map(targetedFileOf);
}

function categorySlugs() {
  const entries = fs.readdirSync(COMPONENTS_DIR, { withFileTypes: true });
  const folders = entries.filter((entry) => entry.isDirectory());
  const names = folders.map((folder) => folder.name);
  return sortedAlphabetically(names);
}

async function manifestOf(slug: string) {
  const manifestPath = path.join(COMPONENTS_DIR, slug, '_manifest.ts');
  if (!fs.existsSync(manifestPath)) {
    return null;
  }
  const loaded = await import(pathToFileURL(manifestPath).href);
  const manifest: ComponentManifest = loaded.manifest;
  return manifest;
}

function componentFileExists(slug: string, name: string) {
  const filePath = path.join(COMPONENTS_DIR, slug, `${name}.tsx`);
  const exists = fs.existsSync(filePath);
  if (!exists) {
    console.warn(`skipped ${slug}/${name}: the file does not exist yet`);
  }
  return exists;
}

async function categoryOf(slug: string) {
  const manifest = await manifestOf(slug);
  if (!manifest) {
    return null;
  }
  const writtenEntries = manifest.filter((entry) =>
    componentFileExists(slug, entry.name)
  );
  const entries = writtenEntries.map((entry) => ({
    ...entry,
    category: slug,
  }));
  const category: CatalogCategory = { slug, name: titleOf(slug), entries };
  return category;
}

function isCategory(value: CatalogCategory | null): value is CatalogCategory {
  return value !== null;
}

export async function collectCatalog() {
  const loaded = await Promise.all(categorySlugs().map(categoryOf));
  return loaded.filter(isCategory);
}

export function componentItemsOf(
  categories: CatalogCategory[]
): RegistryItemDefinition[] {
  return categories.flatMap((category) =>
    category.entries.map((entry) => {
      const entryPath = path.join(
        COMPONENTS_DIR,
        category.slug,
        `${entry.name}.tsx`
      );
      const parts = localPartsOf(entryPath);
      const { registryDependencies, dependencies } = mergedDependencies([
        entryPath,
        ...parts,
      ]);
      return {
        name: entry.name,
        type: 'registry:component',
        title: entry.title,
        description: entry.description,
        files: componentFilesOf(entryPath, parts),
        dependencies,
        registryDependencies,
        categories: ['components', category.slug],
      };
    })
  );
}

export function hookItemsOf(): RegistryItemDefinition[] {
  if (!fs.existsSync(HOOKS_DIR)) {
    return [];
  }
  const files = fs
    .readdirSync(HOOKS_DIR)
    .filter((file) => file.endsWith('.ts'));
  return files.map((file) => {
    const name = file.replace(/\.ts$/, '');
    const relativePath = `registry/ndeko/hooks/${file}`;
    const { registryDependencies, dependencies } = dependenciesOf(
      path.join(ROOT, relativePath)
    );
    return {
      name,
      type: 'registry:hook',
      title: titleOf(name),
      description: `The ${name} hook used by Ndeko UI components.`,
      files: [{ path: relativePath, type: 'registry:hook' }],
      dependencies,
      registryDependencies: registryDependencies.filter(
        (dependency) => dependency !== 'theme'
      ),
      categories: ['hooks'],
    };
  });
}

function previewModuleOf(category: CatalogCategory) {
  const imports = category.entries.map(
    (entry) =>
      `import ${identifierOf(entry.name)} from '@/registry/ndeko/components/${category.slug}/${entry.name}';`
  );
  const rows = category.entries.map(
    (entry) => `  '${entry.name}': ${identifierOf(entry.name)},`
  );
  return [
    GENERATED_NOTICE,
    "import type { ComponentType } from 'react';",
    '',
    ...imports,
    '',
    'export const previews: Record<string, ComponentType> = {',
    ...rows,
    '};',
    '',
  ].join('\n');
}

function catalogModuleOf(categories: CatalogCategory[]) {
  const loaders = categories.map(
    (category) => `  '${category.slug}': () => import('./${category.slug}'),`
  );
  const data = JSON.stringify(categories, null, 2);
  return [
    GENERATED_NOTICE,
    "import type { ComponentType } from 'react';",
    '',
    "import type { CatalogCategory } from '../_catalog/types';",
    '',
    `export const catalog: CatalogCategory[] = ${data};`,
    '',
    'export const loaders: Record<',
    '  string,',
    '  () => Promise<{ previews: Record<string, ComponentType> }>',
    '> = {',
    ...loaders,
    '};',
    '',
  ].join('\n');
}

export function writePreviewModules(categories: CatalogCategory[]) {
  fs.mkdirSync(GENERATED_DIR, { recursive: true });
  for (const category of categories) {
    const target = path.join(GENERATED_DIR, `${category.slug}.ts`);
    fs.writeFileSync(target, previewModuleOf(category));
  }
  const catalogTarget = path.join(GENERATED_DIR, 'catalog.ts');
  fs.writeFileSync(catalogTarget, catalogModuleOf(categories));
}
